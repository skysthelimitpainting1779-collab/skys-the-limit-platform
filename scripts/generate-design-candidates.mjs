import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import sharp from 'sharp';

const PACK_ROOT = 'C:/Users/Johnny Cage/Documents/antigravity/.source/skys-signature-design-drive-pack/skys-signature-design-drive-pack';
const REPO_ROOT = 'C:/Users/Johnny Cage/Documents/antigravity/skys-the-limit-platform';
const OUTPUT_DIR = path.join(REPO_ROOT, 'public/design-lab/candidates');

if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

const manifestPath = path.join(PACK_ROOT, '00-guidance/drive-pack-manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

const getSha256 = (filePath) => {
  const buf = fs.readFileSync(filePath);
  return crypto.createHash('sha256').update(buf).digest('hex');
};

const processedAssets = [];

for (const item of manifest.assets) {
  const origPath = path.join(PACK_ROOT, item.dest);
  if (!fs.existsSync(origPath)) {
    console.error(`Source image missing: ${origPath}`);
    continue;
  }

  const origSha256 = getSha256(origPath);
  const baseName = path.basename(item.dest, path.extname(item.dest));
  const isApprovedBrand = item.status === 'approved-brand-asset';

  let localRelPath;
  let destPath;

  if (isApprovedBrand) {
    localRelPath = `/brand/sky-logo-illustrated-badge.jpg`;
    destPath = path.join(REPO_ROOT, 'public/brand/sky-logo-illustrated-badge.jpg');
    fs.copyFileSync(origPath, destPath);
  } else {
    localRelPath = `/design-lab/candidates/${baseName}.webp`;
    destPath = path.join(OUTPUT_DIR, `${baseName}.webp`);
    
    // Resize & convert to WebP under 500KB budget
    await sharp(origPath)
      .resize({ width: 1440, withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile(destPath);
  }

  const derivativeSha256 = getSha256(destPath);
  const meta = await sharp(destPath).metadata();

  processedAssets.push({
    id: item.asset_id || `CANDIDATE-${baseName.toUpperCase()}`,
    sourceIdentifier: item.drive_file_id,
    localPath: localRelPath,
    originalPackPath: item.dest,
    originalSha256: origSha256,
    derivativeSha256: derivativeSha256,
    width: meta.width,
    height: meta.height,
    status: item.status,
    allowedUses: item.allowed_uses,
    prohibitedUses: item.prohibited_uses,
    recommendedPlacement: item.recommended_use
  });
}

const registryContent = `// Auto-generated by scripts/generate-design-candidates.mjs
export interface DesignAsset {
  id: string;
  sourceIdentifier: string;
  localPath: string;
  originalPackPath: string;
  originalSha256: string;
  derivativeSha256: string;
  width: number;
  height: number;
  status: 'approved-brand-asset' | 'unverified-unlisted-candidate' | 'needs-source-verification' | 'needs-source-verification-high-risk';
  allowedUses: string[];
  prohibitedUses: string[];
  recommendedPlacement: string;
}

export const DESIGN_ASSET_REGISTRY: Record<string, DesignAsset> = ${JSON.stringify(
  processedAssets.reduce((acc, asset) => {
    acc[asset.id] = asset;
    return acc;
  }, {}),
  null,
  2
)};

export function isCandidateAllowedInCurrentEnv(): boolean {
  if (typeof window !== 'undefined') {
    // Client-side evaluation
    return process.env.NEXT_PUBLIC_SIGNATURE_DESIGN_PREVIEW === 'true';
  }
  // Server-side evaluation
  const isProduction = process.env.VERCEL_ENV === 'production' || process.env.NODE_ENV === 'production';
  const previewEnabled = process.env.NEXT_PUBLIC_SIGNATURE_DESIGN_PREVIEW === 'true';
  return !isProduction && previewEnabled;
}

export function getSafeAssetPath(assetId: string, fallbackPath = '/brand/sky-logo-illustrated-badge.jpg'): string {
  const asset = DESIGN_ASSET_REGISTRY[assetId];
  if (!asset) return fallbackPath;
  if (asset.status === 'approved-brand-asset') return asset.localPath;
  if (isCandidateAllowedInCurrentEnv()) return asset.localPath;
  return fallbackPath;
}
`;

const registryPath = path.join(REPO_ROOT, 'src/design/assets/registry.ts');
const registryDir = path.dirname(registryPath);
if (!fs.existsSync(registryDir)) {
  fs.mkdirSync(registryDir, { recursive: true });
}
fs.writeFileSync(registryPath, registryContent);
console.log(`Successfully processed ${processedAssets.length} assets into registry.ts and public/design-lab/candidates.`);
